/* ค่าที่ต้องตรงกับแอป — อ่านจากแอปตอนสร้าง */
function appFacts() {
  const app = readFileSync(new URL("../CareSignal-App.html", import.meta.url), "utf8");
  const cad = app.match(/cadence:\{stable:(\d+), watch:(\d+), decline:(\d+), urgent:(\d+)\}/);
  const rules = (app.match(/var ENGINE=\{[\s\S]*?rules:\{([\s\S]*?)\n {2}\},/) || ["", ""])[1].match(/(R\d+|B\d+):\{nm:/g) || [];
  const sig = [...app.matchAll(/\{k:"(S\d)", nm:"([^"]+)"/g)].map((m) => m[2]);
  return { cadence: cad ? { stable: +cad[1], watch: +cad[2], decline: +cad[3], urgent: +cad[4] } : null, nRules: rules.length, signals: sig };
}

function wrapDoc(d) {
  const rec = (s) => { if (s) TEXT.push(String(s)); };
  return {
    h1(t, s) { rec(t); rec(s); CHAPTERS.push({ t }); d.h1(t, s); },
    h2(t) { rec(t); d.h2(t); }, h3(t) { rec(t); d.h3(t); },
    p(t, o) { rec(t); d.p(t, o); },
    bullets(items, o) { items.forEach((i) => rec(typeof i === "object" ? i.b + " " + i.t : i)); d.bullets(items, o); },
    steps(items) { items.forEach((i) => rec(typeof i === "object" ? i.b + " " + i.t : i)); d.steps(items); },
    callout(k, t, b) { rec(t); rec(b); d.callout(k, t, b); },
    table(cols, rows, o) { cols.forEach((c) => rec(c.t)); rows.forEach((r) => r.forEach(rec)); d.table(cols, rows, o); },
    figure(h, cap, draw) { rec(cap); d.figure(h, cap, draw); },
    keep(mm) { d.need(mm); }
  };
}

