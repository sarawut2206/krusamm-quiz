/* ตัวห่อ Doc ที่เก็บข้อความทุกชิ้นไว้ให้เทสต์ตรวจ และนับภาพต่อบท */
function wrapDoc(d) {
  const rec = (s) => { if (s) TEXT.push(String(s)); };
  const W = {
    h1(t, s) { rec(t); rec(s); CHAPTERS.push({ t, figures: 0 }); d.h1(t, s); },
    h2(t) { rec(t); d.h2(t); }, h3(t) { rec(t); d.h3(t); },
    p(t, o) { rec(t); d.p(t, o); },
    bullets(items, o) { items.forEach((i) => { rec(typeof i === "object" ? i.b + " " + i.t : i); }); d.bullets(items, o); },
    steps(items) { items.forEach((i) => { rec(typeof i === "object" ? i.b + " " + i.t : i); }); d.steps(items); },
    callout(k, t, b) { rec(t); rec(b); d.callout(k, t, b); },
    table(cols, rows, o) { cols.forEach((c) => rec(c.t)); rows.forEach((r) => r.forEach(rec)); d.table(cols, rows, o); },
    figure(h, cap, draw) { rec(cap); CHAPTERS[CHAPTERS.length - 1].figures++; d.figure(h, cap, draw); },
    gap(v) { d.gap(v); },
    keep(mm) { d.need(mm); }
  };
  return W;
}


/* อ่านกฎและแผนดูแลจากแอปตอนสร้าง คู่มือจึงตรงกับแอปเสมอ */
function appFacts() {
  const app = readFileSync(new URL("../CareSignal-App.html", import.meta.url), "utf8");
  const blk = app.match(/var ENGINE=\{[\s\S]*?rules:\{([\s\S]*?)\n {2}\},/)[1];
  const rules = [...blk.matchAll(/(R\d+|B\d+):\{nm:"([^"]+)",src:"([^"]+)"\}/g)].map((m) => [m[1], m[2], m[3]]);
  const plan = [...app.matchAll(/\{id:"(P\d)", dom:"[a-z]+", nm:"([^"]+)", how:"([^"]+)", src:"([^"]+)"\}/g)].map((m) => [m[1], m[2], m[3], m[4]]);
  const sig = [...app.matchAll(/\{k:"(S\d)", nm:"([^"]+)", rules:\[([^\]]+)\]/g)].map((m) => [m[1], m[2], m[3].replace(/"/g, "").replace(/,/g, " · ")]);
  return { rules, plan, sig };
}

