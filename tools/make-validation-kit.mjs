export function buildKit() {
  PAGES.length = 0; SINK.reset();
  const fonts = { reg: readTTF(REG), bold: readTTF(BOLD) };
  const pages = [pagePlan(fonts), pageHowTo(fonts), pageConsent(fonts), pageElderA(fonts), pageElderB(fonts),
                 pageFamily(fonts), pageStaff(fonts), pageCards(fonts), pageSurvey(fonts), pageWrap(fonts)];
  KIT_TEXT = SINK.text();
  return { pdf: buildDoc(pages, fonts, { title: TITLE }), pages: pages.length, text: KIT_TEXT };
}

const norm = (s) => String(s).replace(/\\/g, "/").toLowerCase();
if (process.argv[1] && norm(fileURLToPath(import.meta.url)) === norm(process.argv[1])) {
  const r = buildKit();
  mkdirSync(DIR, { recursive: true });
  writeFileSync(OUT, r.pdf);
  console.log("เขียน validation/CareSignal-ValidationKit.pdf · " + r.pages + " หน้า · " + (r.pdf.length / 1024).toFixed(0) + " KB");
}
