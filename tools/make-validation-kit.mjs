/* ---------- ส่วนประกอบที่ใช้ซ้ำในทุกแบบสัมภาษณ์ ---------- */
function qBlock(p, y, no, q, hint, lines) {
  p.text(no + ".", mm(M), mm(y), 9.5, C.brand2, "l", true);
  const ls = p.wrap(q, 9.5, mm(W - 8));
  ls.forEach((ln, i) => p.text(ln, mm(M + 6), mm(y - i * 4.4), 9.5, C.ink, "l", true));
  SINK.add(q);
  let yy = y - ls.length * 4.4;
  if (hint) {
    const hs = p.wrap(hint, 8.5, mm(W - 8));
    hs.forEach((ln, i) => p.text(ln, mm(M + 6), mm(yy - 0.6 - i * 3.8), 8.5, C.ink3));
    SINK.add(hint);
    yy -= hs.length * 3.8 + 0.6;
  }
  const n = lines || 2;
  for (let i = 0; i < n; i++) p.line(mm(M + 6), mm(yy - 3.4 - i * 6), mm(M + W), mm(yy - 3.4 - i * 6), 0.3, C.line);
  return yy - n * 6 - 2;
}

